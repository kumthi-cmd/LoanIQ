"""Guardrails for query_tape: the model's SQL is checked, made safe, then capped.

Where it sits:
    model's tool call -> [sql_guard.check_query] -> tools.query_tape -> read-only DuckDB

BUSINESS:
    Ask the Tape lets a model write SQL against the tape. That SQL is untrusted
    text: a confused model (or a visitor trying to trick it) could ask for another
    file on the server, a write, or a query that never ends. Every call is checked
    here first. A refused call is not an error for the visitor: the reason goes back
    to the model, which usually fixes its query and tries again.

TECH:
    Defence in depth, three layers:
      1. This module. sqlglot (a SQL parser) turns the text into a syntax tree, and
         the tree must pass all of these:
           - exactly one statement, and it is a SELECT (no WITH, UNION, INSERT ...)
           - no SQL comments (-- or /* */), at most max_sql_chars characters
           - every node on an ALLOWLIST: columns, comparisons, AND/OR/NOT, arithmetic,
             CASE, CAST and a short list of functions (COUNT, SUM, AVG, ROUND ...).
             Anything unknown, including file readers such as read_csv and any
             function sqlglot does not recognise, is refused. An allowlist fails
             safe: a new trick is refused because it is not on the list.
           - the only table is `loans`; every column is a tape column or an alias
             defined in the query
         Filter values are then lifted out of the SQL into bound parameters: in
         `ltv > 125 AND state = 'NY'` the 125 and 'NY' become $p1 and $p2 and travel
         separately to DuckDB (the same rule as the grid's filters, loan_query.py).
         Constants that shape the query (ROUND(x, 2), LIMIT 10, GROUP BY 1, a CASE
         label) stay in the SQL, re-rendered by sqlglot, never the raw text.
      2. The row cap: the LIMIT becomes min(the model's LIMIT, max_rows + 1).
      3. The connection (tape_db.py): a read-only DuckDB file with external file
         access off and its settings locked, so even a query that slipped past
         layer 1 could not write or read anything but the tape.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal
from typing import Any, Iterable

import sqlglot
from sqlglot import exp
from sqlglot.errors import ParseError

TAPE_TABLE = "loans"

# TECH: the syntax-tree node classes a query may contain. Grouped for reading.
STRUCTURE = (exp.Select, exp.From, exp.Table, exp.TableAlias, exp.Where, exp.Group, exp.Having,
             exp.Order, exp.Ordered, exp.Limit, exp.Offset, exp.Alias, exp.Column,
             exp.Identifier, exp.Star, exp.Literal, exp.Boolean, exp.Null, exp.Paren,
             exp.Distinct, exp.Subquery, exp.Tuple, exp.Var, exp.Placeholder)
LOGIC = (exp.And, exp.Or, exp.Not, exp.EQ, exp.NEQ, exp.GT, exp.GTE, exp.LT, exp.LTE,
         exp.Is, exp.In, exp.Between, exp.Like, exp.ILike, exp.Case, exp.If, exp.Filter)
ARITHMETIC = (exp.Add, exp.Sub, exp.Mul, exp.Div, exp.Mod, exp.IntDiv, exp.Neg,
              exp.Cast, exp.TryCast, exp.DataType, exp.DataTypeParam)
# BUSINESS: the functions a desk analyst needs over a tape: counts, sums, weighted
#   averages (SUM(x * upb) / SUM(upb)), medians, rounding, dates by year or month.
FUNCTIONS = (exp.Count, exp.Sum, exp.Avg, exp.Min, exp.Max, exp.Median, exp.Stddev,
             exp.StddevPop, exp.StddevSamp, exp.Variance, exp.PercentileCont,
             exp.PercentileDisc, exp.ArgMax, exp.ArgMin, exp.CountIf, exp.Round, exp.Abs,
             exp.Floor, exp.Ceil, exp.Coalesce, exp.Nullif, exp.Greatest, exp.Least,
             exp.Upper, exp.Lower, exp.Length, exp.Substring, exp.Extract, exp.Year,
             exp.Month, exp.TimestampTrunc, exp.DateTrunc)
ALLOWED_NODES = STRUCTURE + LOGIC + ARITHMETIC + FUNCTIONS
# TECH: a literal directly under one of these is a filter value -> bound parameter.
VALUE_PARENTS = (exp.EQ, exp.NEQ, exp.GT, exp.GTE, exp.LT, exp.LTE, exp.In, exp.Between,
                 exp.Like, exp.ILike)


class GuardrailError(ValueError):
    """The query was refused. The message is written for the model to act on.

    BUSINESS: counts as a guardrail failure; two in one question move the
      question to the stronger model (llm.toml).
    """


@dataclass(frozen=True)
class GuardedQuery:
    """A checked query, ready to run.

    TECH:
      sql          the SQL to execute, with $p1, $p2 ... for the bound values and the
                   capped LIMIT; generated by sqlglot from the checked tree
      params       placeholder name -> bound value (str, int or Decimal)
      count_sql    SELECT COUNT(*) over the same query without the cap, to report
                   "1,234 rows match" when the cap cuts the result (same params)
      display_sql  the model's query, re-rendered and indented, with its values in
                   place, for the screen ("every answer shows its SQL")
      fetch_limit  rows fetched: max_rows + 1, or less if the model asked for fewer
    """
    sql: str
    params: dict[str, Any]
    count_sql: str
    display_sql: str
    fetch_limit: int


def parse_single_select(sql: str, max_chars: int) -> exp.Select:
    """Text -> one SELECT tree, or GuardrailError.

    TECH: comments are refused before parsing so nothing can hide in them. A
      trailing semicolon is fine; a second statement is not (sqlglot.parse returns
      one tree per statement).
    """
    text = sql.strip().rstrip(";").strip()
    if not text:
        raise GuardrailError("The SQL is empty. Send one SELECT over the loans table.")
    if len(text) > max_chars:
        raise GuardrailError(f"The SQL is longer than {max_chars} characters. Simplify it.")
    if "--" in text or "/*" in text:
        raise GuardrailError("SQL comments are not allowed. Remove -- and /* */.")
    try:
        trees = [t for t in sqlglot.parse(text, read="duckdb") if t is not None]
    except ParseError as exc:
        raise GuardrailError(f"The SQL could not be parsed: {str(exc).splitlines()[0]}") from exc
    if len(trees) != 1:
        raise GuardrailError("Send exactly one statement.")
    tree = trees[0]
    if not isinstance(tree, exp.Select):
        raise GuardrailError(f"Only SELECT is allowed, not {type(tree).__name__.upper()}. "
                             "WITH and UNION are not supported; use a subquery.")
    return tree


def check_nodes(tree: exp.Expression) -> None:
    """Every node must be on the allowlist. TECH: names the first offender for the model."""
    for node in tree.walk():
        if not isinstance(node, ALLOWED_NODES):
            name = node.sql(dialect="duckdb")[:60] if isinstance(node, exp.Func) else type(node).__name__
            raise GuardrailError(f"Not allowed in query_tape: {name}. Use plain SELECT with "
                                 "columns, comparisons, CASE and aggregate functions.")


def defined_names(tree: exp.Expression) -> tuple[set[str], set[str]]:
    """(column aliases, table aliases) defined anywhere in the query, lower case."""
    aliases = {a.alias.lower() for a in tree.find_all(exp.Alias) if a.alias}
    tables = {t.name.lower() for t in tree.find_all(exp.TableAlias) if t.name}
    return aliases, tables


def check_tables(tree: exp.Expression) -> None:
    """The only table is `loans`, with no schema or file path in front."""
    for table in tree.find_all(exp.Table):
        if table.name.lower() != TAPE_TABLE or table.args.get("db") or table.args.get("catalog"):
            raise GuardrailError(f"Unknown table {table.sql(dialect='duckdb')!r}. "
                                 f"The only table is {TAPE_TABLE}.")


def check_columns(tree: exp.Expression, columns: Iterable[str]) -> None:
    """Every column is a tape column or an alias defined in the query.

    TECH: DuckDB names are case-insensitive, so comparisons are lower case. A
      qualifier (l.fico) must be `loans` or a table alias from this query.
    """
    known = {c.lower() for c in columns}
    aliases, tables = defined_names(tree)
    for col in tree.find_all(exp.Column):
        if isinstance(col.this, exp.Star):
            continue
        name, qualifier = col.name.lower(), col.table.lower()
        if qualifier and qualifier not in tables | {TAPE_TABLE}:
            raise GuardrailError(f"Unknown table or alias {col.table!r} in {col.sql()!r}.")
        if name not in known and name not in aliases:
            raise GuardrailError(f"Unknown column {col.name!r}. Call list_columns to see the "
                                 "tape's columns.")


def literal_value(lit: exp.Literal) -> Any:
    """A literal node -> its Python value. TECH: decimals stay exact (Decimal, not float)."""
    if lit.is_string:
        return lit.this
    text = lit.this
    return int(text) if text.lstrip("-").isdigit() else Decimal(text)


def bind_values(tree: exp.Select) -> dict[str, Any]:
    """Replace every filter value with a named parameter ($p1, $p2 ...).

    TECH: NAMED, not positional `?`: sqlglot's find_all walks the tree breadth
      first, which is not the order the SQL is printed in, so a list of values for
      `?` marks could bind 125 to a date column. A name ties each value to its own
      placeholder whatever the walk order. DuckDB takes the values as a dict.
      Changes the tree in place.
    """
    params: dict[str, Any] = {}
    for lit in list(tree.find_all(exp.Literal)):
        parent = lit.parent
        if isinstance(parent, exp.Tuple) and isinstance(parent.parent, exp.In):
            parent = parent.parent
        if isinstance(parent, VALUE_PARENTS):
            name = f"p{len(params) + 1}"
            params[name] = literal_value(lit)
            lit.replace(exp.Placeholder(this=name))
    return params


def fetch_limit_for(tree: exp.Select, max_rows: int) -> int:
    """The LIMIT to run with: the model's own LIMIT if smaller, else max_rows + 1.

    TECH: a LIMIT that is not a plain whole number (LIMIT ? or an expression) is refused.
    """
    cap = max_rows + 1
    limit = tree.args.get("limit")
    if limit is None:
        return cap
    value = limit.expression
    if not (isinstance(value, exp.Literal) and not value.is_string and value.this.isdigit()):
        raise GuardrailError("LIMIT must be a whole number.")
    return min(int(value.this), cap)


def check_query(sql: str, columns: Iterable[str], max_rows: int, max_chars: int) -> GuardedQuery:
    """Check the model's SQL and build the safe, capped, parameterized query.

    BUSINESS: the single gate between what a model writes and the tape.
    TECH: raises GuardrailError with a reason the model can act on. The order of
      checks is shape -> nodes -> tables -> columns, so the first message is about
      the biggest problem.
    """
    tree = parse_single_select(sql, max_chars)
    check_nodes(tree)
    check_tables(tree)
    check_columns(tree, columns)
    display_sql = tree.sql(dialect="duckdb", pretty=True)
    fetch_limit = fetch_limit_for(tree, max_rows)
    params = bind_values(tree)
    count_sql = f"SELECT COUNT(*) FROM ({tree.sql(dialect='duckdb')}) AS q"
    capped = tree.limit(fetch_limit, copy=True)
    return GuardedQuery(sql=capped.sql(dialect="duckdb"), params=params, count_sql=count_sql,
                        display_sql=display_sql, fetch_limit=fetch_limit)
